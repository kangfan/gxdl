using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;
using UnityEngine.UI;

namespace Gxdl.EditorTools
{
    /// <summary>
    /// 把运行时代码生成的 UI 层级抓取成 prefab，并生成配套的 View 绑定类。
    ///
    /// 目的：界面坐标、层级与九宫格保持与现有实现完全一致，
    /// 避免手工重画 750x1334 界面引入的偏差。抓取后用 View 的序列化字段
    /// 取代原先按 GameObject 名字字符串查找的脆弱绑定。
    /// </summary>
    public static class UiPrefabCapture
    {
        const string PrefabRoot = "Assets/Resources/UI";
        const string ScriptRoot = "Assets/Scripts/Modules";
        const string ViewTemplate = @"// <auto-generated />
// 由 UiPrefabCapture 生成，字段名对应 prefab 中的节点路径。
// 重新生成会覆盖手写修改，如需自定义逻辑请写在分部类的另一部分。

namespace Gxdl.Modules
{{
    public partial class {0} : UiModule
    {{
        public override string ModuleId => ""{0}"";

{1}
    }}
}}
";

        [MenuItem("Gxdl/UI/抓取当前界面为 Prefab", priority = 100)]
        static void CaptureFromScene()
        {
            var canvas = FindCanvas();
            if (canvas == null)
            {
                EditorUtility.DisplayDialog("抓取失败", "场景中找不到 Canvas", "确定");
                return;
            }

            var selection = Selection.activeGameObject;
            var target = selection != null ? selection : canvas.gameObject;
            string moduleName;

            if (!AskModuleName(target.name, out moduleName)) return;

            Capture(target, moduleName);
        }

        /// <summary>取场景中的主 Canvas。优先用 ScreenSpaceCamera 的那个，否则取第一个。</summary>
        static Canvas FindCanvas()
        {
            var candidates = UnityEngine.Object.FindObjectsOfType<Canvas>();
            if (candidates == null || candidates.Length == 0) return null;

            for (var i = 0; i < candidates.Length; i++)
            {
                if (candidates[i].renderMode == RenderMode.ScreenSpaceCamera) return candidates[i];
            }

            return candidates[0];
        }

        static bool AskModuleName(string suggestion, out string moduleName)
        {
            moduleName = null;
            var input = SanitizeName(suggestion);
            var accepted = UnityEditor.EditorUtility.DisplayDialog(
                "抓取界面",
                "将把选中的层级保存为 prefab，并生成 View 绑定类。\n模块名（建议以 View 结尾）：",
                "抓取",
                "取消");

            if (!accepted) return false;

            moduleName = string.IsNullOrEmpty(input) ? "NewView" : input;
            return true;
        }

        /// <summary>
        /// 抓取指定节点为 prefab，并生成 View 脚本。
        /// 供菜单调用，也可由自测夹具直接调用。
        /// </summary>
        public static string Capture(GameObject root, string moduleName)
        {
            if (root == null) throw new ArgumentNullException(nameof(root));
            if (string.IsNullOrEmpty(moduleName)) throw new ArgumentException("模块名不能为空", nameof(moduleName));

            Directory.CreateDirectory(PrefabRoot);
            Directory.CreateDirectory(ScriptRoot);

            var instance = UnityEngine.Object.Instantiate(root);
            instance.name = moduleName;
            instance.SetActive(true);

            var prefabPath = $"{PrefabRoot}/{moduleName}.prefab";
            var prefab = PrefabUtility.SaveAsPrefabAsset(instance, prefabPath);
            UnityEngine.Object.DestroyImmediate(instance);

            var bindings = CollectBindings(prefab.transform, moduleName);
            WriteView(moduleName, bindings);

            AssetDatabase.SaveAssets();
            AssetDatabase.Refresh();

            Debug.Log($"[UiPrefabCapture] 已生成 {prefabPath}，绑定字段 {bindings.Count} 个");
            return prefabPath;
        }

        struct Binding
        {
            public string FieldName;
            public string ComponentType;
            public string Path;
        }

        /// <summary>
        /// 按节点路径生成唯一字段名。层级用下划线连接，
        /// 保证同一 prefab 内字段名不冲突且可读。
        /// </summary>
        static List<Binding> CollectBindings(Transform root, string moduleName)
        {
            var bindings = new List<Binding>();
            var used = new HashSet<string>();
            Walk(root, root, moduleName, bindings, used);
            return bindings;
        }

        static void Walk(
            Transform root,
            Transform node,
            string moduleName,
            List<Binding> bindings,
            HashSet<string> used)
        {
            if (node != root)
            {
                var componentType = ResolveComponentType(node);
                if (componentType != null)
                {
                    var fieldName = BuildFieldName(root, node);
                    if (used.Add(fieldName))
                    {
                        bindings.Add(new Binding
                        {
                            FieldName = fieldName,
                            ComponentType = componentType,
                            Path = BuildPath(root, node)
                        });
                    }
                }
            }

            for (var i = 0; i < node.childCount; i++) Walk(root, node.GetChild(i), moduleName, bindings, used);
        }

        /// <summary>
        /// 按优先级取节点上最有语义的组件，避免一个节点生成多个字段。
        /// 全部使用全限定名，因为 UnityEditor 下存在同名类型会导致解析歧义。
        /// </summary>
        static string ResolveComponentType(Transform node)
        {
            if (node.GetComponent<UnityEngine.UI.Button>() != null) return "Button";
            if (node.GetComponent<UnityEngine.UI.Text>() != null) return "UnityEngine.UI.Text";
            if (node.GetComponent<UnityEngine.UI.Image>() != null) return "UnityEngine.UI.Image";
            if (node.GetComponent<UnityEngine.UI.RawImage>() != null) return "UnityEngine.UI.RawImage";
            if (node.GetComponent<UnityEngine.UI.ScrollRect>() != null) return "UnityEngine.UI.ScrollRect";
            if (node.GetComponent<UnityEngine.UI.Toggle>() != null) return "UnityEngine.UI.Toggle";
            if (node.GetComponent<UnityEngine.UI.Slider>() != null) return "UnityEngine.UI.Slider";
            return null;
        }

        static string BuildPath(Transform root, Transform node)
        {
            var parts = new List<string>();
            var current = node;
            while (current != null && current != root)
            {
                parts.Insert(0, current.name);
                current = current.parent;
            }

            return string.Join("/", parts.ToArray());
        }

        static string BuildFieldName(Transform root, Transform node)
        {
            var path = BuildPath(root, node);
            var segments = path.Split('/');
            var builder = new StringBuilder();
            for (var i = 0; i < segments.Length; i++)
            {
                var segment = SanitizeName(segments[i]);
                if (segment.Length == 0) continue;
                if (builder.Length == 0) builder.Append(char.ToLowerInvariant(segment[0]));
                else builder.Append(char.ToUpperInvariant(segment[0]));
                if (segment.Length > 1) builder.Append(segment.Substring(1));
            }

            var fieldName = builder.Length == 0 ? "element" : builder.ToString();
            if (char.IsDigit(fieldName[0])) fieldName = "node" + fieldName;
            return fieldName;
        }

        static string SanitizeName(string raw)
        {
            if (string.IsNullOrEmpty(raw)) return string.Empty;
            var builder = new StringBuilder(raw.Length);
            foreach (var character in raw)
            {
                if (char.IsLetterOrDigit(character)) builder.Append(character);
            }

            return builder.ToString();
        }

        static void WriteView(string moduleName, List<Binding> bindings)
        {
            var body = new StringBuilder();
            for (var i = 0; i < bindings.Count; i++)
            {
                var binding = bindings[i];
                body.AppendLine($"        [SerializeField] {binding.ComponentType} {binding.FieldName}; // {binding.Path}");
            }

            if (bindings.Count == 0) body.AppendLine("        // 未发现可绑定的控件");

            var scriptPath = $"{ScriptRoot}/{moduleName}.cs";
            if (File.Exists(scriptPath))
            {
                // 已有手写实现时不覆盖，避免丢失业务逻辑。
                Debug.LogWarning($"[UiPrefabCapture] {scriptPath} 已存在，跳过生成。绑定清单已打印。");
                for (var i = 0; i < bindings.Count; i++)
                {
                    Debug.Log($"  {bindings[i].Path} -> {bindings[i].FieldName}");
                }

                return;
            }

            var content = string.Format(ViewTemplate, moduleName, body.ToString());
            File.WriteAllText(scriptPath, content, new UTF8Encoding(false));
        }
    }
}
